async page => {
  const p=page.context().pages().find(p=>p.url().startsWith('http://127.0.0.1:4186/'));
  if(!p) throw new Error('Expected existing local test journey');
  await p.setViewportSize({width:390,height:844});
  const key='nextcard:adventure:v0.4', errors=[];p.on('pageerror',e=>errors.push(e.message));
  const stored=()=>p.evaluate(k=>localStorage.getItem(k),key);
  const check=(value,message)=>{if(!value)throw new Error(message);};
  const goal=async name=>{await p.getByRole('button',{name:'目标与帮助',exact:true}).click();await p.getByRole('button',{name,exact:true}).click();await p.getByRole('button',{name:'完成',exact:true}).click();};
  await p.reload({waitUntil:'networkidle'});await p.getByRole('button',{name:'继续上次旅程',exact:true}).click();
  await p.getByRole('button',{name:'查看当前线索',exact:true}).click();
  const beforeReview=await stored(), requests=[];
  const observe=r=>{if(r.url().includes('/data/'))requests.push(r.url());};p.on('request',observe);
  await p.getByText('回看最近一次资金核查',{exact:true}).click();
  const review=p.locator('details').filter({has:p.locator('summary').filter({hasText:'回看最近一次资金核查'})}).first();
  const reviewText=await review.innerText();
  check(reviewText.includes('20 金币')&&reviewText.includes('21 金币')&&reviewText.includes('4 金币'),'saved revision missing');
  check(reviewText.includes('原试算')&&reviewText.includes('修订计划'),'comparison missing');
  check(await stored()===beforeReview&&requests.length===0,'review changed save or fetched data');
  p.off('request',observe);
  check(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'review horizontal overflow');
  await p.screenshot({path:'output/playwright/saved-funding-review-mobile.png',fullPage:true});
  await p.getByRole('button',{name:'返回营地',exact:true}).click();await goal('资金安排');
  await p.getByRole('button',{name:'试试资金安排',exact:true}).click();
  await p.getByRole('button',{name:'不能支付',exact:true}).click();
  const input=p.getByLabel('调整后的参与金额（金币）');await input.fill('20');await input.press('Tab');
  await p.getByRole('button',{name:'提交判断并保存计划',exact:true}).click();
  const result=p.locator('#research-d1-result');
  check(JSON.stringify(await result.locator('.button.gold').allTextContents())===JSON.stringify(['调整这份计划']),'funding recommendation has wrong primary');
  const beforeAdjust=await stored();await result.getByRole('button',{name:'调整这份计划',exact:true}).click();
  await p.waitForFunction(()=>{const el=document.activeElement;if(!(el instanceof HTMLInputElement))return false;const b=el.getBoundingClientRect();return b.top>=0&&b.bottom<=innerHeight;});
  const focus=await input.evaluate(el=>({active:el===document.activeElement,top:el.getBoundingClientRect().top,bottom:el.getBoundingClientRect().bottom}));
  check(focus.active&&await stored()===beforeAdjust&&await result.count()===1,'adjust should only focus existing draft');
  await input.fill('10');await input.press('Tab');check(await result.count()===0,'edited plan retains stale result');
  check(await stored()===beforeAdjust,'draft edit wrote saved observation');
  await p.getByRole('button',{name:'提交判断并保存计划',exact:true}).click();
  await goal('历史比较');
  const historyPrimary=await result.locator('.button.gold').innerText();
  check(/历史对照台/.test(historyPrimary),'goal change did not update primary');
  await result.locator('.button.gold').click();await p.getByRole('heading',{name:'历史对照台',exact:true}).waitFor();
  await goal('资金安排');
  await p.getByRole('button',{name:'锁定并查看同期资料',exact:true}).click();
  await p.getByLabel('本案例结果相对同期基准').selectOption('underperform');
  await p.getByLabel('这次主要依据什么？').selectOption('根据同日期的数字比较');
  await p.getByRole('button',{name:'提交这次研究',exact:true}).click();
  const historyResult=p.locator('#research-d2-result'), fundingPrimary=await historyResult.locator('.button.gold').innerText();
  check(fundingPrimary==='切换 · 资金安排台','history result primary ignores funding goal');
  await historyResult.locator('.button.gold').click();await p.getByRole('heading',{name:'资金安排台',exact:true}).waitFor();
  check(errors.length===0,'page errors: '+errors.join(';'));
  return {reviewText,reviewReadOnly:true,reviewDataRequests:requests,adjustFocus:focus,feedbackClearsOnlyOnEdit:true,changedGoalPrimary:historyPrimary,historyPrimary:fundingPrimary,openedRecommendedTask:true,errors};
}
